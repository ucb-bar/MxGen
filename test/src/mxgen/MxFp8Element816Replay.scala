package mxgen

import chisel3._
import chiseltest._
import org.scalatest.flatspec.AnyFlatSpec
import org.scalatest.matchers.should.Matchers

/** Element replay for C[8][16] of the fp8 128x128 requant test (the corrupt block).
  * Runs each K-tile (16 products) through the mesh PE at accFormat=(4,5)=am4 -- EXACT for kk0-7,
  * narrower for kk8+. Prints running out_bf16 per (ko,kk) so we can diff against the Spike golden
  * ([SPK816]) and find the first product whose flush/compute diverges. c resets to 0 each K-tile
  * (Spike does the cross-K-tile accumulate in BF16 after block scaling, outside the PE).
  */
class MxFp8Element816Replay extends AnyFlatSpec with ChiselScalatestTester with Matchers {
  val config = MxConfig.mxGemmini.copy(productFormat = MxFormat(4, 4), accFormat = MxFormat(4, 5))
  val E4M3_EXP = 4; val E4M3_SIG = 4
  val A: Seq[Int] = Seq(0x1b,0xa3,0x3a,0x32,0x28,0x28,0xac,0x1d,0x3d,0x3b,0xbd,0xa8,0x8d,0x36,0xac,0x94,0xa5,0x32,0x34,0xbb,0x39,0x3e,0x3a,0xaa,0x39,0x34,0x3c,0xa9,0x2d,0xad,0xa4,0x01,0x29,0xa5,0x09,0x98,0x11,0x35,0x07,0x21,0xa5,0xb1,0x98,0xba,0x3a,0x18,0xb2,0xa1,0x25,0x89,0xa9,0x17,0xa0,0xa4,0x1d,0x98,0x10,0x2a,0x27,0x22,0xb2,0xac,0xa1,0x9b,0x1c,0x88,0xa1,0xa2,0x1a,0xa1,0x22,0x07,0x0c,0x89,0x83,0x11,0xa9,0x27,0x10,0x9a,0x13,0x88,0xa0,0x81,0x24,0x06,0x14,0x24,0x02,0x8d,0x94,0x39,0x9c,0x23,0x14,0x20,0x23,0x2d,0xa1,0xa0,0x91,0xa4,0x96,0x1c,0xb9,0x97,0x1e,0x16,0x14,0x15,0x86,0x09,0x00,0x09,0xa4,0x26,0x02,0x81,0xa0,0x21,0x02,0x9a,0x20,0x19,0x95,0xa2,0x97,0x83)   // A[8][k], k=0..127
  val B: Seq[Int] = Seq(0xb1,0x9a,0xb1,0xab,0x33,0xb9,0xa8,0x28,0xae,0x29,0xb8,0x2a,0x99,0x25,0xa5,0x2b,0xad,0x29,0x2c,0xa0,0x2b,0x30,0x34,0xb8,0xad,0xaf,0xa9,0xa4,0xb8,0xb1,0x08,0x02,0xb0,0xa9,0xa8,0x91,0xaa,0x36,0x9b,0xab,0xb3,0xb0,0xae,0xb0,0x88,0x30,0x2c,0x27,0x2a,0xa9,0x35,0x33,0xaa,0x34,0x32,0x25,0xaa,0x1d,0xaf,0xa4,0xb1,0xba,0xac,0xb2,0xa1,0x36,0x35,0x2a,0xb2,0x27,0xa8,0x0b,0xb6,0x39,0x9e,0xb2,0xa9,0xb7,0xb8,0x16,0xae,0x27,0xb0,0xb4,0xb2,0x2f,0x2b,0x37,0xb2,0x21,0x38,0xb1,0x28,0xa4,0x1a,0xba,0x97,0x99,0x91,0x29,0x07,0x25,0x32,0x1c,0xa2,0x35,0x21,0x0a,0xa9,0x3b,0xad,0xa2,0xb1,0x2e,0x2f,0xb5,0x0a,0xb9,0xa4,0xb7,0xb1,0x1d,0x2b,0x84,0xac,0x2d,0x30,0x39)   // B[k][16]

  behavior of "fp8 element C[8][16] replay"
  it should "print running acc per (ko,kk)" in {
    test(new MxFpMulHarnessBf16Out_NewIO(config, lut = false, latency = 0)) { h =>
      h.io.type_a.exp.poke(E4M3_EXP.U); h.io.type_a.sig.poke(E4M3_SIG.U)
      h.io.type_w.exp.poke(E4M3_EXP.U); h.io.type_w.sig.poke(E4M3_SIG.U)
      h.io.enable.poke(true.B)
      val aW = h.io.in_activation.getWidth; val wW = h.io.in_weights.getWidth
      for (ko <- 0 until 8) {
        var c = 0
        for (kk <- 0 until 16) {
          val k = ko*16 + kk
          h.io.in_activation.poke(BigInt(A(k) & 0xFF).U(aW.W))
          h.io.in_weights.poke(BigInt(B(k) & 0xFF).U(wW.W))
          h.io.c_raw.poke((c & 0xFFFF).U(16.W))
          h.clock.step(1)
          val out = h.io.out_bf16.peek().litValue.toInt & 0xFFFF
          val inf = ((out >> 7) & 0xFF) == 0xFF && (out & 0x7F) == 0
          println(f"[DUT816] ko=$ko%d kk=$kk%2d Acode=0x${A(k)}%02X Bcode=0x${B(k)}%02X c=0x$c%04X -> out=0x$out%04X" + (if (inf) "  <== INF" else ""))
          c = out
        }
        println(f"[DUT816] ko=$ko%d END Ct(bf16)=0x$c%04X")
      }
      h.io.enable.poke(false.B)
    }
  }
}
